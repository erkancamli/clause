_LOOKUP: dict[str, str] = {}
for _code, _name in NAMES.items():
    _LOOKUP[_name.lower()] = _code
for _name, _code in ALIASES.items():
    _LOOKUP[_name.lower()] = _code
for _name, _post in US_STATES.items():
    _LOOKUP[_name.lower()] = "US"
    _LOOKUP[_post.lower()] = "US"
# Georgia the state and Georgia the country share a name. USGS writes the
# country as "Georgia" too, but the state far more often in its feed is by
# postal code, and a Caucasus event is rare enough that the country wins here.
_LOOKUP["georgia"] = "GE"
# "CA" is California in USGS text, never Canada, which it writes out.
_LOOKUP["ca"] = "US"

_BY_LENGTH = sorted(_LOOKUP, key=len, reverse=True)


def code_for(text: str) -> str | None:
    """The country a piece of place text names, or None.

    The last comma separated part is tried first, since that is where USGS
    puts the country or state. Then any known name inside the text, longest
    first, which reads "off the east coast of Honshu, Japan" and "south of the
    Kermadec Islands" alike.
    """
    if not text:
        return None
    tail = text.rsplit(",", 1)[-1].strip().rstrip(".")
    found = _LOOKUP.get(tail.lower())
    if found:
        return found
    low = text.lower()
    for name in _BY_LENGTH:
        if len(name) < 4:
            continue
        if re.search(r"(?<![a-z])" + re.escape(name) + r"(?![a-z])", low):
            return _LOOKUP[name]
    return None
